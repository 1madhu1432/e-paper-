function buildPageList(count: number, editionName: string, dateStr: string, volStr: string) {
  const pages = [];
  for (let i = 1; i <= count; i++) {
    pages.push({
      pageNumber: i,
      imageUrl: generateNewspaperSVG(i, editionName, dateStr, volStr, count),
      title: i === 1 ? 'ప్రధాన ముఖ్యాంశాలు (Front Page)' : `పేజీ ${i} - ${editionName}`,
      category: i === 1 ? 'Front Page' : i === 2 ? 'State' : i === 3 ? 'Metro' : i === 4 ? 'Editorial' : i === 5 ? 'Business' : i === 8 ? 'Jobs' : i === 9 ? 'Sports' : 'District',
      viewsCount: 15240 - (i * 850),
      uniqueReaders: 11200 - (i * 600),
      avgTimeSeconds: 140 - (i * 4)
    });
  }
  return pages;
}

